#!/usr/bin/env python3
"""Qiskit / Qiskit Aer experiments for the reversible Shor circuits.

    python run_qiskit.py env                       # record versions
    python run_qiskit.py quick                     # 1-case smoke test (N=15, a=7)
    python run_qiskit.py counts   [--N 15 21 35] [--families ...]
    python run_qiskit.py simulate [--N 15] [--families ...] [--which after|before|both]
    python run_qiskit.py tables                    # CSV summaries from the jsonl logs

Every circuit is generated by families.py/qpe.py (verified exhaustively by
verify.py / verify2.py), converted 1:1 to a QuantumCircuit, and compiled with ONE
fixed transpiler configuration (CONFIG below).  Results are appended to
results/*.jsonl, so an interrupted run can simply be restarted.
"""
import argparse, json, os, platform, sys, time
from math import gcd, pi

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from qpe import shor_circuit                                   # noqa: E402
from analysis import (order, identity_blocks, success_probability,  # noqa: E402
                      recovers_factor, wilson, compare_counts)

CONFIG = {
    "basis_gates": ["rz", "sx", "x", "cx"],
    "optimization_level": 1,
    "seed_transpiler": 20260929,
    "coupling_map": None,
    "shots": 1024,
    "seed_simulator_base": 20260929,
    "statevector_max_qubits": 26,
}
FAMILIES = ["beauregard", "cuccaro", "montgomery"]
OUT = os.path.join(HERE, "results")


# ----------------------------------------------------------------------------
def to_qiskit(circ, measure):
    from qiskit import QuantumCircuit
    qc = QuantumCircuit(circ.nq, len(measure))
    for name, qs, th in circ.ops:
        if name == "h": qc.h(qs[0])
        elif name == "x": qc.x(qs[0])
        elif name == "cx": qc.cx(qs[0], qs[1])
        elif name == "ccx": qc.ccx(qs[0], qs[1], qs[2])
        elif name == "p": qc.p(th, qs[0])
        elif name == "cp": qc.cp(th, qs[0], qs[1])
        elif name == "ccp": qc.mcp(th, [qs[0], qs[1]], qs[2])
        elif name == "swap": qc.swap(qs[0], qs[1])
        elif name == "cswap": qc.cswap(qs[0], qs[1], qs[2])
        else: raise ValueError(name)
    for q, cbit in measure:
        qc.measure(q, cbit)
    return qc


def metrics(qc):
    ops = {k: int(v) for k, v in qc.count_ops().items()}
    m = {"size": int(qc.size()), "depth": int(qc.depth()),
         "multi_qubit": int(qc.num_nonlocal_gates()), "ops": ops,
         "cx": ops.get("cx", 0)}
    # rotation classes (meaningful after transpilation to rz/sx/x/cx)
    clif = tlike = arb = 0
    for inst in qc.data:
        if inst.operation.name == "rz":
            th = float(inst.operation.params[0]) % (pi / 2)
            if min(th, pi / 2 - th) < 1e-9: clif += 1
            elif abs(th - pi / 4) < 1e-9: tlike += 1
            else: arb += 1
    m.update({"rz_clifford": clif, "rz_t_like": tlike, "rz_arbitrary": arb})
    return m


def transpile_fixed(qc):
    from qiskit import transpile
    return transpile(qc, basis_gates=CONFIG["basis_gates"],
                     optimization_level=CONFIG["optimization_level"],
                     seed_transpiler=CONFIG["seed_transpiler"],
                     coupling_map=CONFIG["coupling_map"])


def bases(N):
    return [a for a in range(2, N) if gcd(a, N) == 1]


def done_keys(path):
    keys = set()
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            for line in f:
                try: keys.add(json.loads(line)["key"])
                except Exception: pass
    return keys


def append(path, rec):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "a", encoding="utf-8") as f:
        f.write(json.dumps(rec) + "\n")


# ----------------------------------------------------------------------------
def cmd_env(_):
    import qiskit
    try:
        import qiskit_aer; aer = qiskit_aer.__version__
    except Exception:
        aer = None
    rec = {"python": sys.version.split()[0], "qiskit": qiskit.__version__,
           "qiskit_aer": aer, "platform": platform.platform(),
           "processor": platform.processor(), "cpu_count": os.cpu_count(),
           "config": CONFIG}
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "environment.json"), "w", encoding="utf-8") as f:
        json.dump(rec, f, indent=2)
    print(json.dumps(rec, indent=2))


def cmd_counts(args):
    path = os.path.join(OUT, "counts.jsonl")
    done = done_keys(path)
    for N in args.N:
        for fam in args.families:
            for a in (args.bases or bases(N)):
                for rem in (False, True):
                    key = f"{fam}|{N}|{a}|{'after' if rem else 'before'}"
                    if key in done: continue
                    t0 = time.time()
                    circ, meas, info = shor_circuit(fam, N, a, remove_identity=rem)
                    qc = to_qiskit(circ, meas)
                    t1 = time.time()
                    tqc = transpile_fixed(qc)
                    t2 = time.time()
                    rec = {"key": key, "family": fam, "N": N, "a": a,
                           "stage": "after" if rem else "before",
                           "n": info["n"], "t": info["t"], "qubits": qc.num_qubits,
                           "order": order(a, N), "identity_blocks": identity_blocks(N, a, info["t"]),
                           "blocks_kept": sum(1 for b in info["blocks"] if b[2] != "removed"),
                           "logical": metrics(qc), "transpiled": metrics(tqc),
                           "build_s": round(t1 - t0, 3), "transpile_s": round(t2 - t1, 3)}
                    append(path, rec)
                    print(f"{key:32s} q={qc.num_qubits:2d} logical={rec['logical']['size']:6d} "
                          f"-> basis={rec['transpiled']['size']:7d} cx={rec['transpiled']['cx']:6d} "
                          f"depth={rec['transpiled']['depth']:6d} ({t2 - t1:.1f}s)", flush=True)


def cmd_simulate(args):
    from qiskit_aer import AerSimulator
    path = os.path.join(OUT, "simulate.jsonl")
    done = done_keys(path)
    stages = {"after": [True], "before": [False], "both": [False, True]}[args.which]
    for N in args.N:
        for fam in args.families:
            for a in (args.bases or bases(N)):
                for rem in stages:
                    key = f"{fam}|{N}|{a}|{'after' if rem else 'before'}"
                    if key in done: continue
                    circ, meas, info = shor_circuit(fam, N, a, remove_identity=rem)
                    qc = to_qiskit(circ, meas)
                    tqc = transpile_fixed(qc) if args.circuit == "basis" else qc
                    method = args.method
                    if method == "auto":
                        method = ("statevector" if qc.num_qubits <= CONFIG["statevector_max_qubits"]
                                  else "matrix_product_state")
                    seed = CONFIG["seed_simulator_base"] + 1000 * N + a
                    sim = AerSimulator(method=method, seed_simulator=seed)
                    t0 = time.time()
                    res = sim.run(tqc, shots=CONFIG["shots"]).result()
                    wall = time.time() - t0
                    raw = res.get_counts()
                    counts = {}
                    for bits, c in raw.items():
                        y = int(bits.replace(" ", ""), 2)
                        counts[y] = counts.get(y, 0) + int(c)
                    t = info["t"]; Q = 2 ** t
                    p_exact, P, acc = success_probability(N, a, t)
                    shots = sum(counts.values())
                    k = sum(c for y, c in counts.items() if recovers_factor(y, Q, a, N))
                    lo, hi = wilson(k, shots)
                    stats = compare_counts(counts, P, shots)
                    rec = {"key": key, "family": fam, "N": N, "a": a,
                           "stage": "after" if rem else "before", "circuit": args.circuit,
                           "qubits": qc.num_qubits, "method": method, "seed_simulator": seed,
                           "shots": shots, "order": order(a, N),
                           "identity_blocks": identity_blocks(N, a, t),
                           "p_exact": p_exact, "success_count": k, "p_hat": k / shots,
                           "wilson95": [lo, hi], "p_exact_in_ci": lo <= p_exact <= hi,
                           **stats, "wall_s": round(wall, 2),
                           "counts": {str(y): c for y, c in sorted(counts.items())}}
                    append(path, rec)
                    print(f"{key:32s} {method:20s} p_hat={k/shots:.4f} exact={p_exact:.4f} "
                          f"TVD={stats['tvd']:.4f} chi2_p={stats['chi2_p']:.3f} "
                          f"off-support={stats['off_support']} ({wall:.1f}s)", flush=True)


def cmd_tables(_):
    import csv
    cpath = os.path.join(OUT, "counts.jsonl")
    if os.path.exists(cpath):
        rows = [json.loads(l) for l in open(cpath, encoding="utf-8")]
        with open(os.path.join(OUT, "counts.csv"), "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(["family", "N", "a", "stage", "order", "identity_blocks", "blocks_kept",
                        "qubits", "logical_size", "logical_depth", "logical_multiqubit",
                        "basis_size", "basis_depth", "basis_cx", "rz_t_like", "rz_arbitrary",
                        "transpile_s"])
            for r in rows:
                L, T = r["logical"], r["transpiled"]
                w.writerow([r["family"], r["N"], r["a"], r["stage"], r["order"], r["identity_blocks"],
                            r["blocks_kept"], r["qubits"], L["size"], L["depth"], L["multi_qubit"],
                            T["size"], T["depth"], T["cx"], T["rz_t_like"], T["rz_arbitrary"],
                            r["transpile_s"]])
        print("wrote results/counts.csv")
    spath = os.path.join(OUT, "simulate.jsonl")
    if os.path.exists(spath):
        rows = [json.loads(l) for l in open(spath, encoding="utf-8")]
        with open(os.path.join(OUT, "simulate.csv"), "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(["family", "N", "a", "stage", "order", "identity_blocks", "qubits", "method",
                        "shots", "p_exact", "success_count", "p_hat", "wilson_lo", "wilson_hi",
                        "p_exact_in_ci", "tvd", "chi2", "dof", "chi2_p", "off_support", "wall_s"])
            for r in rows:
                w.writerow([r["family"], r["N"], r["a"], r["stage"], r["order"], r["identity_blocks"],
                            r["qubits"], r["method"], r["shots"], f"{r['p_exact']:.4f}",
                            r["success_count"], f"{r['p_hat']:.4f}", f"{r['wilson95'][0]:.4f}",
                            f"{r['wilson95'][1]:.4f}", r["p_exact_in_ci"], f"{r['tvd']:.4f}",
                            f"{r['chi2']:.2f}", r["dof"], f"{r['chi2_p']:.3f}", r["off_support"],
                            r["wall_s"]])
        print("wrote results/simulate.csv")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["env", "quick", "counts", "simulate", "tables"])
    ap.add_argument("--N", type=int, nargs="+", default=[15, 21, 35])
    ap.add_argument("--families", nargs="+", default=FAMILIES, choices=FAMILIES)
    ap.add_argument("--bases", type=int, nargs="+", default=None)
    ap.add_argument("--which", default="after", choices=["after", "before", "both"])
    ap.add_argument("--circuit", default="basis", choices=["basis", "logical"])
    ap.add_argument("--method", default="auto",
                    choices=["auto", "statevector", "matrix_product_state"])
    args = ap.parse_args()
    if args.cmd == "env": cmd_env(args)
    elif args.cmd == "counts": cmd_counts(args)
    elif args.cmd == "simulate": cmd_simulate(args)
    elif args.cmd == "tables": cmd_tables(args)
    elif args.cmd == "quick":
        args.N = [15]; args.bases = [7]; args.which = "both"
        cmd_env(args); cmd_counts(args); cmd_simulate(args); cmd_tables(args)


if __name__ == "__main__":
    main()
